// Headless click-through of the hosted demo (or any build): cash-out, refunded cash-out, top-up, history.
// Usage: BASE=https://mbanyadev.github.io/nimcfa/ node scripts/e2e-browser-demo.mjs  (needs playwright-core + Chrome)
import { chromium } from 'playwright-core'
const BASE = process.env.BASE
const browser = await chromium.launch({ executablePath: process.env.CHROME ?? '/usr/bin/google-chrome', headless: true })
const ctx = await browser.newContext({ viewport: { width: 430, height: 932 }, locale: 'en-US' })
const page = await ctx.newPage()
const t0 = Date.now(); const log = (...a) => console.log(((Date.now() - t0) / 1000).toFixed(1) + 's', ...a)
page.on('dialog', d => { log('dialog:', d.message().split('\n').join(' | ')); d.accept() })
page.on('console', m => { if (['error', 'warning', 'info'].includes(m.type())) log('console', m.type(), m.text().slice(0, 200)) })
page.on('pageerror', e => log('pageerror', e.message))
const waitStatus = (re) => page.locator('.status b').filter({ hasText: re }).waitFor({ timeout: 150000 })
const timeline = async () => (await page.locator('.timeline li').allInnerTexts()).map(s => s.replace(/\n/g, ' ')).join(' | ')
await page.goto(BASE)
log('banners:', (await page.locator('.banner').allInnerTexts().catch(() => [])).join(' / '))
await page.getByRole('button', { name: 'Connect Nimiq Pay' }).waitFor({ timeout: 120000 }); log('connect visible')
log('banners:', (await page.locator('.banner').allInnerTexts()).join(' / '))
await page.getByRole('button', { name: 'Connect Nimiq Pay' }).click()
await page.locator('.acct b').waitFor({ timeout: 60000 }); log('connected', await page.locator('.acct').innerText())
async function order(kind, xaf, phone, re) {
  if (kind === 'onramp') await page.getByRole('button', { name: /Top up/i }).first().click()
  else await page.getByRole('button', { name: /Cash out/i }).first().click()
  await page.getByLabel('FCFA').fill(String(xaf))
  await page.locator('.phone input').fill(phone)
  await page.locator('.quote b').filter({ hasText: /NIM/ }).waitFor({ timeout: 30000 })
  await page.waitForTimeout(500)
  await page.locator('button.primary').click()
  await page.locator('.status').waitFor({ timeout: 60000 })
  try { await waitStatus(re) } catch (e) { log('TIMEOUT', await page.locator('.status').innerText(), await timeline()); throw e }
  log(kind, xaf, phone, '->', (await page.locator('.status').innerText()).replace(/\n/g, ' · '))
  log('  timeline:', await timeline())
  await page.locator('button.primary').click()
  await page.waitForTimeout(1000)
}
await order('offramp', 1000, '670000000', /^Paid$/)
await order('offramp', 500, '690000001', /^Refunded$/)
await order('onramp', 1000, '650000000', /NIM delivered/)
await page.getByRole('button', { name: /History/i }).first().click()
await page.waitForTimeout(1500)
log('history:', (await page.locator('.history li').allInnerTexts()).map(s => s.replace(/\n/g, ' ')).join(' | '))
log('balance', await page.locator('.acct').innerText())
await page.screenshot({ path: process.env.SHOT ?? 'e2e-demo.png' })
await browser.close()
log('E2E OK')
