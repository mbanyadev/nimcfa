/** Whole numbers in the UI language: 10,000 (EN) or 10 000 (FR). */
export function fmtInt(n: number, locale = 'fr-FR') { return Math.round(n).toLocaleString(locale) }
export function fmtXaf(n: number, locale = 'fr-FR') { return `${fmtInt(n, locale)} FCFA` }
export function fmtNim(luna: number, locale = 'en-US', digits = 2) { return (luna / 1e5).toLocaleString(locale, { maximumFractionDigits: digits }) }
/** "1 NIM = 0.62 FCFA", with enough decimals to be meaningful. */
export function fmtRate(xafPerNim: number, locale = 'en-US') {
  const d = xafPerNim >= 100 ? 0 : xafPerNim >= 1 ? 2 : xafPerNim >= 0.01 ? 4 : 6
  return `1 NIM = ${xafPerNim.toLocaleString(locale, { maximumFractionDigits: d, minimumFractionDigits: Math.min(d, 2) })} FCFA`
}
